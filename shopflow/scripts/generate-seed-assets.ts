export function ensureSeedAssets() {
  const publicDir = path.join(process.cwd(), "public", "images", "products");
  const uploadsSeedDir = path.join(process.cwd(), "uploads", "seed");

  if (!fs.existsSync(publicDir)) {
    fs.mkdirSync(publicDir, { recursive: true });
  }
  if (!fs.existsSync(uploadsSeedDir)) {
    fs.mkdirSync(uploadsSeedDir, { recursive: true });
  }

  // Generate 15 product images
  for (let i = 1; i <= 15; i++) {
    const prodId = `PROD-${String(i).padStart(3, "0")}`;
    const filePath = path.join(publicDir, `${prodId}.jpg`);
    if (!fs.existsSync(filePath)) {
      fs.writeFileSync(filePath, MINIMAL_JPEG);
    }
  }

  // Generate sample evidence files
  const evidenceFiles = [
    "damage-headphones.jpg",
    "coffee-maker-crack.jpg",
    "laptop-screen.jpg",
    "wrong-keyboard.jpg",
    "dead-pixels.jpg",
    "broken-box.jpg"
  ];

  for (const filename of evidenceFiles) {
    const filePath = path.join(uploadsSeedDir, filename);
    if (!fs.existsSync(filePath)) {
      fs.writeFileSync(filePath, MINIMAL_JPEG);
    }
  }
}

if (require.main === module) {
  ensureSeedAssets();
  console.log("Seed assets successfully generated.");
}
